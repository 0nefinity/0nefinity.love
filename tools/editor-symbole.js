// SVG eines Symbols als Text; jeder Einbau bekommt eigene Masken-Kennungen.
window.oneSymbolSvg = function (name, attrs) {
  const s = window.oneSymbole.symbole[name];
  if (!s) throw new Error('Symbol fehlt: ' + name);
  const id = 'sym-' + name + '-' + (++window.oneSymbolSvg.n);
  return '<svg viewBox="' + s.viewBox.join(' ') + '" ' + (attrs || '') + '>' + s.inhalt.split('{id}').join(id) + '</svg>';
};
window.oneSymbolSvg.n = 0;
